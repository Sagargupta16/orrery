// The drawio.svg format: one file that is the SVG picture and, opened in draw.io, the editable
// diagram, stored the way draw.io saves its own .drawio.svg files.
import { execFile } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, sep } from "node:path";
import { promisify } from "node:util";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { FORMATS, formatOf, type RenderResult, renderModel } from "../src/render/index.ts";
import type { Skin, ThemeName } from "../src/types.ts";
import { model, must, ROOT, SAMPLE, xmlProblems } from "./helpers.ts";

const PROLOG =
  '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Do not edit this file with editors other than draw.io -->\n';
const ENTITIES: Record<string, string> = { lt: "<", gt: ">", quot: '"', apos: "'", amp: "&" };
/** What an XML parser hands back for an attribute value, in one pass so `&amp;lt;` stays `&lt;`. */
const attributeValue = (value: string) =>
  value.replace(/&(#\d+|#x[\da-f]+|\w+);/gi, (_, e: string) =>
    e[0] === "#"
      ? String.fromCodePoint(Number(e[1] === "x" ? `0${e.slice(1)}` : e.slice(1)))
      : (ENTITIES[e] ?? `&${e};`),
  );

const THEMES: ThemeName[] = ["light", "dark"];
const SKINS: Skin[] = ["classic", "stage"];
const runs: Partial<Record<Skin, RenderResult>> = {};

beforeAll(async () => {
  for (const skin of SKINS)
    runs[skin] = await renderModel({
      model: model(SAMPLE),
      formats: ["svg", "drawio", "drawio.svg"],
      themes: THEMES,
      name: "orders",
      skin,
    });
});

const artifact = (skin: Skin, format: string, theme: ThemeName): string => {
  const a = must(
    runs[skin]?.artifacts.find((x) => x.format === format && x.theme === theme),
    `${skin} ${format} ${theme}`,
  );
  if (typeof a.data !== "string") throw new Error(`${format} is binary`);
  return a.data;
};

describe("drawio.svg", () => {
  for (const skin of SKINS)
    it.each(THEMES)(`${skin}: is the svg with the draw.io model in content (%s)`, (theme) => {
      const file = artifact(skin, "drawio.svg", theme);
      expect(file.startsWith(`${PROLOG}<svg content="`)).toBe(true);
      expect(xmlProblems(file)).toEqual([]);
      const content = must(file.match(/<svg content="([^"]*)"/), "content")[1] ?? "";
      expect(content).not.toMatch(/[\t\n\r]/);
      expect(attributeValue(content)).toBe(artifact(skin, "drawio", theme));
      expect(xmlProblems(attributeValue(content))).toEqual([]);
      // Take the prolog and the attribute away and the picture is the svg format's, byte for byte.
      const picture = file.slice(PROLOG.length).replace(` content="${content}"`, "");
      expect(picture).toBe(artifact(skin, "svg", theme));
    });

  it("is one of the formats, named by its whole extension", () => {
    expect(FORMATS).toContain("drawio.svg");
    expect(formatOf("out/x.drawio.svg")).toBe("drawio.svg");
    expect(formatOf("OUT/X.DRAWIO.SVG")).toBe("drawio.svg");
    expect(formatOf("x.svg")).toBe("svg");
    expect(formatOf("x.drawio")).toBe("drawio");
    expect(formatOf("x.yaml")).toBeUndefined();
  });
});

describe("orrery render -f drawio.svg", () => {
  let dir = "";
  const cli = (...args: string[]) =>
    promisify(execFile)(process.execPath, [join(ROOT, "src", "main.ts"), ...args], { cwd: dir });

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), "orrery-editable-"));
    writeFileSync(join(dir, "x.yaml"), SAMPLE);
  });
  afterAll(() => rmSync(dir, { recursive: true, force: true }));

  it("writes x-light.drawio.svg and x-dark.drawio.svg for --theme both", async () => {
    const out = join(dir, "both");
    await cli("render", "x.yaml", "-f", "drawio.svg", "--theme", "both", "-o", `${out}${sep}`);
    expect(readdirSync(out).sort()).toEqual(["x-dark.drawio.svg", "x-light.drawio.svg"]);
    expect(readFileSync(join(out, "x-dark.drawio.svg"), "utf8").startsWith(PROLOG)).toBe(true);
  });

  it("includes drawio.svg in -f all", async () => {
    const out = join(dir, "all");
    await cli("render", "x.yaml", "-f", "all", "-o", `${out}${sep}`);
    expect(readdirSync(out).sort()).toEqual([
      "x.drawio",
      "x.drawio.svg",
      "x.html",
      "x.mmd",
      "x.png",
      "x.sequence.svg",
      "x.svg",
      "x.tsx",
    ]);
  });
});
