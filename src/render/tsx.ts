// SVG -> React component (TSX). The SVG is rendered with a placeholder id prefix, which becomes a
// useId() value, so two copies of the component on one page never share gradient or clip ids.

import type { Scene } from "../types.ts";
import { renderSvg } from "./svg.ts";

const UID = "SDWUID";

const KEEP = new Set([
  "viewBox",
  "gradientUnits",
  "gradientTransform",
  "patternUnits",
  "patternTransform",
  "preserveAspectRatio",
  "clipPathUnits",
  "maskUnits",
  "maskContentUnits",
  "spreadMethod",
  "stdDeviation",
  "baseFrequency",
  "numOctaves",
  "markerWidth",
  "markerHeight",
  "refX",
  "refY",
  "fx",
  "fy",
]);

function attrName(name: string): string {
  if (name === "class") return "className";
  if (name === "xlink:href") return "xlinkHref";
  if (name === "xmlns:xlink") return "xmlnsXlink";
  if (name === "xml:space") return "xmlSpace";
  if (name.startsWith("aria-") || name.startsWith("data-") || KEEP.has(name)) return name;
  return name.replace(/[-:]([a-z])/g, (_, c: string) => c.toUpperCase());
}

function attrValue(name: string, value: string): string {
  const decoded = value
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
  if (name === "style") {
    const obj = decoded
      .split(";")
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => {
        const [k = "", ...v] = d.split(":");
        const key = k.trim().replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
        return `${JSON.stringify(key)}: ${JSON.stringify(v.join(":").trim())}`;
      });
    return `{{ ${obj.join(", ")} }}`;
  }
  if (decoded.includes(UID)) return templateLiteral(decoded);
  return /["\\{}]/.test(decoded) ? `{${JSON.stringify(decoded)}}` : `"${decoded}"`;
}

/** A JSX expression holding a template literal, with the id placeholder swapped for `${uid}`. */
function templateLiteral(s: string): string {
  const body = s
    .replace(/[`\\]/g, "\\$&")
    .replaceAll("$", "\\$")
    // biome-ignore lint/suspicious/noTemplateCurlyInString: emits a placeholder into the generated TSX
    .replaceAll(`${UID}-`, "${uid}-");
  return `{\`${body}\`}`;
}

function jsxText(s: string): string {
  return s.replace(/[{}]/g, (c) => `{"${c}"}`);
}

export function componentName(title: string | undefined, fallback: string): string {
  const base = (title || fallback)
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
  const name = base || "Diagram";
  return /^[A-Z]/.test(name) ? name : `Diagram${name}`;
}

export function renderTsx(scene: Scene, name: string): string {
  const svg = renderSvg(scene, { idPrefix: UID });
  const out: string[] = [];
  let depth = 2;
  const indent = () => "  ".repeat(depth);
  let inStyle = false;
  const tokens = svg.match(/<\/?[a-zA-Z][^>]*>|[^<]+/g) ?? [];
  for (const tok of tokens) {
    if (tok.startsWith("</")) {
      const tag = tok.slice(2, -1).trim();
      if (tag === "style") inStyle = false;
      depth -= 1;
      out.push(`${indent()}</${tag}>`);
      continue;
    }
    if (tok.startsWith("<")) {
      const selfClosing = tok.endsWith("/>");
      const inner = tok.slice(1, selfClosing ? -2 : -1);
      const [tag = ""] = inner.split(/\s/, 1);
      const attrs = [...inner.slice(tag.length).matchAll(/([\w:.-]+)="([^"]*)"/g)].map(
        ([, k = "", v = ""]) => `${attrName(k)}=${attrValue(k, v)}`,
      );
      if (tag === "svg") attrs.push("{...props}");
      out.push(
        `${indent()}<${tag}${attrs.length ? ` ${attrs.join(" ")}` : ""}${selfClosing ? " />" : ">"}`,
      );
      if (!selfClosing) {
        depth += 1;
        if (tag === "style") inStyle = true;
      }
      continue;
    }
    const textNode = tok.replace(/\n/g, "");
    if (!textNode.trim()) continue;
    out.push(`${indent()}${inStyle ? templateLiteral(textNode) : jsxText(textNode)}`);
  }
  return [
    "// Generated by stackdraw. Edit the diagram spec and re-render instead of editing this file.",
    `import { type SVGProps, useId } from "react";`,
    "",
    `export default function ${name}(props: SVGProps<SVGSVGElement>) {`,
    `  const uid = useId().replace(/[^A-Za-z0-9_-]/g, "");`,
    "  return (",
    ...out,
    "  );",
    "}",
    "",
  ].join("\n");
}
